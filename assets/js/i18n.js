(function () {
  const store = {
    get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } }
  };

  function detectLang() {
    const url = new URLSearchParams(location.search).get("lang");
    if (url === "en" || url === "ar") return url;
    return store.get("nile-lang") || "ar";
  }

  window.NILE.lang = detectLang();
  window.NILE.t = (key) => (I18N[NILE.lang] && I18N[NILE.lang][key]) || I18N.ar[key] || key;

  window.NILE.applyLang = function (lang) {
    NILE.lang = lang;
    store.set("nile-lang", lang);
    const d = document.documentElement;
    d.lang = lang;
    d.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = NILE.t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = NILE.t(el.dataset.i18nHtml); });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = NILE.t(el.dataset.i18nPh); });
    const titleKey = document.body.dataset.titleKey || "meta.title";
    document.title = NILE.t(titleKey);
    document.dispatchEvent(new CustomEvent("nile:lang", { detail: lang }));
  };

  document.addEventListener("DOMContentLoaded", () => {
    NILE.applyLang(NILE.lang);

    document.querySelectorAll(".lang-btn").forEach((b) =>
      b.addEventListener("click", () => NILE.applyLang(NILE.lang === "ar" ? "en" : "ar")));

    const header = document.querySelector(".site-header");
    const onScroll = () => header && header.classList.toggle("scrolled", scrollY > 30);
    addEventListener("scroll", onScroll, { passive: true });
    onScroll();

    const toggle = document.querySelector(".menu-toggle");
    const links = document.querySelector(".nav-links");
    if (toggle && links) {
      toggle.addEventListener("click", () => {
        const open = links.classList.toggle("open");
        toggle.setAttribute("aria-expanded", open);
      });
      links.querySelectorAll("a").forEach((a) => a.addEventListener("click", () => {
        links.classList.remove("open");
        toggle.setAttribute("aria-expanded", "false");
      }));
    }

    document.querySelectorAll("[data-wa]").forEach((a) => {
      a.href = "https://wa.me/" + NILE.whatsapp;
      a.target = "_blank";
      a.rel = "noopener";
    });

    const y = document.getElementById("year");
    if (y) y.textContent = new Date().getFullYear();
  });
})();
